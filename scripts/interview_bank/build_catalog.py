#!/usr/bin/env python3
"""Build pipe-delimited Q|A catalog files (100+ per category). Run once or when extending."""

from __future__ import annotations

from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
CAT_DIR = SCRIPTS / "interview_bank" / "catalog"
INTERMEDIATE_DIR = CAT_DIR / "intermediate"


def w(name: str, lines: list[tuple[str, str]]) -> None:
    CAT_DIR.mkdir(parents=True, exist_ok=True)
    path = CAT_DIR / f"{name}.txt"
    body = "\n".join(f"{q}|{a}" for q, a in lines)
    path.write_text(body + "\n", encoding="utf-8")
    print(f"{name}: {len(lines)} questions -> {path}")


def w_intermediate(name: str, lines: list[tuple[str, str]]) -> None:
    INTERMEDIATE_DIR.mkdir(parents=True, exist_ok=True)
    path = INTERMEDIATE_DIR / f"{name}.txt"
    body = "\n".join(f"{q}|{a}|intermediate" for q, a in lines)
    path.write_text(body + "\n", encoding="utf-8")
    print(f"{name} (intermediate): {len(lines)} questions -> {path}")


def qa(term: str, ans: str) -> tuple[str, str]:
    return (f"Explain {term} in beginner-friendly terms.", ans)


def qwhat(term: str, ans: str) -> tuple[str, str]:
    return (f"What is {term}?", ans)


def qwhen(term: str, ans: str) -> tuple[str, str]:
    return (f"When should you use {term}?", ans)


